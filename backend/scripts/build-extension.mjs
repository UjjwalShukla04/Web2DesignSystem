// Bundles the browser extension's content script (extension/src/content.ts, which
// imports the shared in-page extraction code from src/inpage.ts) into extension/content.js.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const extension = fileURLToPath(new URL("../../extension/", import.meta.url));

await build({
  entryPoints: [`${extension}src/content.ts`],
  outfile: `${extension}content.js`,
  bundle: true,
  format: "iife",
  target: "chrome114",
  charset: "utf8",
  banner: { js: "// Generated by `npm run build:extension` (backend/). Edit extension/src/content.ts instead." },
  logLevel: "info",
});
